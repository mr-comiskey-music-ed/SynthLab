/** Targets share the plain defaults, with the filter envelope off unless a patch needs it. */
const target = (o: Partial<SynthParams>): SynthParams => ({ ...DEFAULT_SYNTH_PARAMS, filterEnvAmount: 0, vco2Level: 0, ...o });
/**
 * Where the student starts: the target with a few graded settings knocked off.
 * Anything not graded already matches the target, so matching the graded settings
 * is enough to sound right.
 */
const startFrom = (t: SynthParams, o: Partial<SynthParams>): SynthParams => ({ ...t, ...o });

